public class Operadores{

    public static void main (String[] args){
        //Operadores aritimeticos
        int a = 10;
        int b = 5;
System.out.println (a + b);
System.out.println (a - b);
System.out.println (a / b);
System.out.println (a * b);
System.out.println (a % b);

    int c = 20;
    int d = 15;
System.out.println (c == d);
System.out.println (c |= d);
System.out.println (c > d);
System.out.println (c < d);
System.out.println (c >= d);
System.out.println (c <= d);


    boolean e = true;
    boolean f = false;
System.out.println (e && f);
System.out.println (e || f);
System.out.println (!e);


    int g = 10;

    g+=5;
    g-=5;
    g/=5;
    g*=5;
    g%=5;

    }
}